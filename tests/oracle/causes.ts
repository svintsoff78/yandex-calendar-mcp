/** Распределяет нарушения по причинам; ключ "—" — не покрытые ничем. */
export function groupByCause(findings: readonly Finding[]): Map<string, Finding[]> {
  const groups = new Map<string, Finding[]>();
  for (const finding of findings) {
    const cause = CAUSES.find((c) => c.match(finding));
    const key = cause?.id ?? "—";
    const list = groups.get(key);
    if (list) list.push(finding);
    else groups.set(key, [finding]);
  }
  return groups;
}
